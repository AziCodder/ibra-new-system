#!/bin/sh
# Локальный запуск: `docker compose up -d` должен давать готовое к работе
# приложение. Миграции накатываются здесь, а не руками, — иначе после каждого
# `git pull` с новой ревизией API поднимался бы на старой схеме и падал на
# первом же запросе.
set -e

echo "Применяю миграции…"
python -m alembic upgrade head

echo "Запускаю API с автоперезагрузкой на :8000…"
exec uvicorn app.main:app --host 0.0.0.0 --port 8000 --reload
